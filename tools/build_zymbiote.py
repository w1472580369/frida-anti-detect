#!/usr/bin/env python3
"""
Rebuild the four prebuilt Android zymbiote injection stubs from
src/linux/helpers/zymbiote.c using the Android NDK.

The committed artifacts are static-pie shared modules located at:

    src/linux/helpers/artifacts/native/{arm64,arm,x86_64,x86}/zymbiote.elf

They are embedded into frida-server and connect back to an abstract unix
socket whose name must match the one generated by linux-host-session.vala.
This script recompiles them so the socket prefix stays in sync.
"""

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

FRIDA_CORE = Path(__file__).resolve().parent.parent / "frida" / "subprojects" / "frida-core"
HELPERS = FRIDA_CORE / "src" / "linux" / "helpers"
ARTIFACTS = HELPERS / "artifacts" / "native"


def configure(frida_root):
    """Point the helper/artifact paths at an arbitrary frida source tree."""
    global FRIDA_CORE, HELPERS, ARTIFACTS
    FRIDA_CORE = Path(frida_root).resolve() / "subprojects" / "frida-core"
    HELPERS = FRIDA_CORE / "src" / "linux" / "helpers"
    ARTIFACTS = HELPERS / "artifacts" / "native"


def ndk_root() -> Path:
    root = os.environ.get("ANDROID_NDK_ROOT") or os.environ.get("ANDROID_NDK_HOME")
    if not root:
        sys.exit("ANDROID_NDK_ROOT must point at the Android NDK")
    root = Path(root)
    if not root.exists():
        sys.exit(f"NDK does not exist: {root}")
    return root


def find_clang(ndk: Path) -> Path:
    clang = ndk / "toolchains" / "llvm" / "prebuilt" / "linux-x86_64" / "bin" / "clang"
    if not clang.exists():
        sys.exit(f"NDK clang not found: {clang}")
    return clang


# (artifact arch, clang --target, extra flags)
TARGETS = [
    ("arm64", "aarch64-none-linux-android21", ["-mbranch-protection=bti"]),
    ("arm", "armv7a-none-linux-androideabi21", ["-marm"]),
    ("x86_64", "x86_64-none-linux-android21", []),
    ("x86", "i686-none-linux-android21", ["-fno-stack-protector"]),
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="verify the artifacts contain no frida-zymbiote strings")
    ap.add_argument("--frida", default=str(Path(__file__).resolve().parent.parent / "frida"),
                    help="frida source root (default: <repo>/frida)")
    args = ap.parse_args()
    configure(args.frida)

    ndk = ndk_root()
    clang = find_clang(ndk)
    lds = HELPERS / "helper.lds"
    src = HELPERS / "zymbiote.c"

    common = [
        "-fPIE", "-fvisibility=hidden", "-fno-function-sections",
        "-fno-data-sections", "-fno-asynchronous-unwind-tables",
        "-Os", "-ffreestanding",
    ]
    link = [
        "-nostdlib", "-shared", f"-Wl,-T,{lds}",
        "-Wl,-z,max-page-size=4096", "-Wl,--export-dynamic",
    ]

    failures = 0
    for arch, target, extra in TARGETS:
        out = ARTIFACTS / arch / "zymbiote.elf"
        cmd = [str(clang), f"--target={target}", *common, *extra, *link,
               str(src), "-o", str(out)]
        rc = subprocess.run(cmd, capture_output=True, text=True).returncode
        if rc != 0:
            print(f"[FAIL] {arch}")
            failures += 1
            continue

        exports = subprocess.run(["readelf", "--dyn-syms", str(out)],
                                 capture_output=True, text=True).stdout
        n_exports = exports.count("FUNC")
        strings = subprocess.run(["strings", str(out)],
                                 capture_output=True, text=True).stdout
        clean = "frida-zymbiote" not in strings
        print(f"[ok] {arch}: exports={n_exports}, "
              f"frida-string-free={clean}, size={out.stat().st_size}")
        if n_exports < 2 or not clean:
            failures += 1

    if failures:
        sys.exit(f"{failures} architecture(s) failed")


if __name__ == "__main__":
    main()
